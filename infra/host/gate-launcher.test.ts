import { spawn } from "node:child_process"
import { existsSync } from "node:fs"
import {
  chmod,
  mkdir,
  mkdtemp,
  readFile,
  realpath,
  rm,
  writeFile,
} from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"

import { afterAll, beforeAll, describe, expect, it } from "vitest"

import {
  gateLauncher,
  launchedGate,
  launcherSteps,
  type GateLauncherInput,
} from "./gate-launcher.ts"
import type { DaemonSpec } from "./plane-base.ts"

const base: GateLauncherInput = {
  user: "_eidogate",
  groups: ["_eidogate", "_eidoipc"],
  cwd: "/Library/Application Support/Eido/app/packages/gate",
  argv: [
    "/opt/homebrew/bin/node",
    "--import",
    "./src/ts-hooks.ts",
    "./src/main.ts",
  ],
}

const GATE = `'/usr/sbin/chroot' '-u' '_eidogate' '-g' '_eidogate' '-G' '_eidogate,_eidoipc' '/' '/usr/bin/env' '-C' '/Library/Application Support/Eido/app/packages/gate' '/opt/homebrew/bin/node' '--import' './src/ts-hooks.ts' './src/main.ts'`

describe("gateLauncher", () => {
  const script = gateLauncher(base)
  const body = script.split("\n").filter((text) => !text.startsWith("#"))

  it("is this zsh script", () => {
    expect(script).toBe(
      [
        "#!/bin/zsh -f",
        "# Eido gate launcher (#823): generated by `host plane`; edit the generator, not this file.",
        "# launchd runs it as root. It pipes the passphrase of the System keychain item com.eido.gate.keychain-unlock",
        "# into the gate's stdin, drops to _eidogate and execs the gate, which unlocks its keychain (#821).",
        "set -u",
        "ulimit -c 0",
        "export EIDO_GATE_KEYCHAIN_UNLOCK=stdin",
        "if ! '/usr/bin/env' '-i' 'HOME=/var/root' '/usr/bin/security' 'find-generic-password' '-s' 'com.eido.gate.keychain-unlock' '/Library/Keychains/System.keychain' >/dev/null 2>&1; then",
        "  print -u2 -r -- 'eido gate launcher: the System keychain item com.eido.gate.keychain-unlock is missing or unreadable; starting the gate with no passphrase, so it stays locked'",
        `  exec ${GATE} </dev/null`,
        "fi",
        `'/usr/bin/env' '-i' 'HOME=/var/root' '/usr/bin/security' 'find-generic-password' '-s' 'com.eido.gate.keychain-unlock' '-w' '/Library/Keychains/System.keychain' | exec ${GATE}`,
        "",
      ].join("\n")
    )
  })

  it("reads the passphrase from the named System keychain item and pipes it into the gate, never through a variable", () => {
    const piped = body.filter((text) => text.includes("'-w'"))
    expect(piped).toEqual([
      `'/usr/bin/env' '-i' 'HOME=/var/root' '/usr/bin/security' 'find-generic-password' '-s' 'com.eido.gate.keychain-unlock' '-w' '/Library/Keychains/System.keychain' | exec ${GATE}`,
    ])
    // No `$` outside quotes: nothing is expanded, so no variable, argument or substitution holds
    // the passphrase. Single-quoted words are taken out first; `'\''` escapes are inside them.
    const unquoted = body.map((text) => text.replaceAll(/'[^']*'/g, "''"))
    expect(unquoted.filter((text) => text.includes("$"))).toEqual([])
    // Nothing echoes or traces it: no xtrace, verbose mode or tee.
    expect(
      unquoted.filter((text) => /set -[a-z]*[xv]|\btee\b/.test(text))
    ).toEqual([])
  })

  it("drops to the gate user and its groups before it execs the gate, with the stdin unlock mode set", () => {
    const exportAt = body.indexOf("export EIDO_GATE_KEYCHAIN_UNLOCK=stdin")
    const execs = body
      .map((text, index) => ({ text, index }))
      .filter(({ text }) => text.includes("exec "))
    expect(execs.map(({ index }) => index > exportAt)).toEqual([true, true])
    // Every line that runs node runs it straight after chroot's -u, -g, -G and `/`.
    const drop =
      "exec '/usr/sbin/chroot' '-u' '_eidogate' '-g' '_eidogate' '-G' '_eidogate,_eidoipc' '/' '/usr/bin/env' '-C' '/Library/Application Support/Eido/app/packages/gate' '/opt/homebrew/bin/node' "
    const runsNode = body.filter((text) =>
      text.includes("'/opt/homebrew/bin/node'")
    )
    expect(runsNode.map((text) => text.includes(drop))).toEqual([true, true])
  })

  it("starts the gate with no stdin and says why on stderr when the item is missing or unreadable", () => {
    const probe = body.findIndex((text) => text.startsWith("if ! "))
    expect(body.slice(probe + 1, probe + 4)).toEqual([
      "  print -u2 -r -- 'eido gate launcher: the System keychain item com.eido.gate.keychain-unlock is missing or unreadable; starting the gate with no passphrase, so it stays locked'",
      `  exec ${GATE} </dev/null`,
      "fi",
    ])
  })

  it("quotes every value, so a path cannot inject a command", () => {
    const evil = gateLauncher({
      ...base,
      cwd: "/tmp/a'; touch /tmp/pwned; '$(id)",
      argv: ["/opt/node", "=cmd", "~root", "*"],
    })
    expect(evil).toContain(
      ` '-C' '/tmp/a'\\''; touch /tmp/pwned; '\\''$(id)' '/opt/node' '=cmd' '~root' '*'`
    )
  })

  it("refuses a program that is relative or that env would read as an assignment", () => {
    expect(() => gateLauncher({ ...base, argv: ["node"] })).toThrow(
      'the gate\'s program "node" must be an absolute path without "="'
    )
    expect(() => gateLauncher({ ...base, argv: ["/opt/A=1/node"] })).toThrow(
      "must be an absolute path"
    )
  })
})

describe("launchedGate", () => {
  it("runs the launcher as root and keeps the gate's env, cwd and logs", () => {
    const gate: DaemonSpec = {
      label: "com.eido.plane.gate",
      user: "_eidogate",
      group: "_eidogate",
      args: ["/opt/node", "./src/main.ts"],
      cwd: "/app/packages/gate",
      env: { EIDO_GATE_KEYCHAIN_PATH: "/k/eido.keychain-db" },
      outLog: "/l/out",
      errLog: "/l/err",
      keepAlive: true,
    }
    expect(launchedGate(gate, "/app/gate-launcher.zsh")).toEqual({
      ...gate,
      user: "root",
      group: "wheel",
      args: ["/bin/zsh", "-f", "/app/gate-launcher.zsh"],
    })
  })
})

describe("launcherSteps", () => {
  it("removes whatever is at the path, writes the script, then makes it root's and writable by no one else", () => {
    const steps = launcherSteps("/app/gate-launcher.zsh", "script\n")
    expect(steps).toEqual([
      { argv: ["/bin/rm", "-f", "/app/gate-launcher.zsh"] },
      { argv: ["/usr/bin/tee", "/app/gate-launcher.zsh"], stdin: "script\n" },
      { argv: ["/usr/sbin/chown", "root:wheel", "/app/gate-launcher.zsh"] },
      { argv: ["/bin/chmod", "0555", "/app/gate-launcher.zsh"] },
    ])
  })
})

// Runs the generated script under the real zsh, with fakes for security and chroot (which need
// root) and a fake gate that records what it was given.
describe.runIf(existsSync("/bin/zsh"))("the launcher under zsh", () => {
  let dir = ""
  let cwd = ""
  let script = ""
  const passphrase = "correct horse 'battery' $(staple)"

  beforeAll(async () => {
    dir = await realpath(await mkdtemp(join(tmpdir(), "eido-launcher-")))
    // A cwd a careless script would split or run: quotes, spaces and a substitution.
    cwd = join(dir, "app's dir $(touch pwned)")
    await mkdir(cwd)
    const q = (value: string) => `'${value.replaceAll("'", `'\\''`)}'`
    const out = (name: string) => q(join(dir, name))
    const fake = async (name: string, lines: string[]) => {
      const path = join(dir, name)
      await writeFile(path, ["#!/bin/sh", ...lines, ""].join("\n"))
      await chmod(path, 0o755)
      return path
    }
    const security = await fake("security", [
      `printf '%s\\n' "$*" >> ${out("security.calls")}`,
      `env >> ${out("security.env")}`,
      `[ -f ${out("item")} ] || { echo 'security: The specified item could not be found in the keychain.' >&2; exit 44; }`,
      `case " $* " in *" -w "*) cat ${out("item")}; echo ;; *) echo 'class: "genp"' ;; esac`,
    ])
    // chroot(8) changes to `/`, then runs the rest in the same process.
    const chroot = await fake("chroot", [
      `printf '%s\\n' "$@" > ${out("chroot.args")}`,
      `while [ "$1" != / ]; do shift; done; shift`,
      "cd /",
      `exec "$@"`,
    ])
    const gate = await fake("gate", [
      `echo $$ > ${out("gate.pid")}`,
      `printf '%s\\n' "$@" > ${out("gate.args")}`,
      `pwd -P > ${out("gate.cwd")}`,
      `if [ -t 0 ]; then echo tty; else echo notty; fi > ${out("gate.tty")}`,
      `ulimit -c > ${out("gate.core")}`,
      `env > ${out("gate.env")}`,
      `cat > ${out("gate.stdin")}`,
    ])
    script = join(dir, "gate-launcher.zsh")
    await writeFile(
      script,
      gateLauncher({
        ...base,
        cwd,
        argv: [gate, "--flag", "it's"],
        tools: { security, chroot, env: "/usr/bin/env" },
      })
    )
  })

  afterAll(async () => {
    await rm(dir, { recursive: true, force: true })
  })

  const run = async () => {
    for (const name of ["security.calls", "security.env", "gate.stdin"])
      await rm(join(dir, name), { force: true })
    const child = spawn("/bin/zsh", ["-f", script], {
      env: {
        PATH: "/usr/bin:/bin",
        EIDO_GATE_KEYCHAIN_PATH: "/k/eido.keychain-db",
      },
      stdio: ["ignore", "ignore", "pipe"],
    })
    let stderr = ""
    child.stderr.on("data", (chunk: Buffer) => {
      stderr += chunk.toString()
    })
    const code = await new Promise<number | null>((done) => {
      child.on("close", done)
    })
    const read = (name: string) => readFile(join(dir, name), "utf8")
    return { pid: child.pid, code, stderr, read }
  }

  it("pipes the item's passphrase into the gate's stdin as the gate's own process, keeping env and cwd", async () => {
    await writeFile(join(dir, "item"), passphrase)
    const { pid, code, stderr, read } = await run()
    expect(code).toBe(0)
    expect(stderr).toBe("")
    expect(await read("gate.stdin")).toBe(`${passphrase}\n`)
    expect(await read("gate.tty")).toBe("notty\n")
    expect(await read("gate.pid")).toBe(`${String(pid)}\n`)
    expect(await read("gate.args")).toBe("--flag\nit's\n")
    expect(await read("gate.cwd")).toBe(`${cwd}\n`)
    expect(await read("gate.core")).toBe("0\n")
    expect(await read("chroot.args")).toContain(
      "-u\n_eidogate\n-g\n_eidogate\n-G\n_eidogate,_eidoipc\n/\n"
    )
    const env = await read("gate.env")
    expect(env).toContain("EIDO_GATE_KEYCHAIN_UNLOCK=stdin\n")
    expect(env).toContain("EIDO_GATE_KEYCHAIN_PATH=/k/eido.keychain-db\n")
    expect(env).not.toContain("horse")
    // security ran with root's home and none of the gate's settings, and only with fixed arguments.
    const securityEnv = await read("security.env")
    expect(securityEnv).toContain("HOME=/var/root\n")
    expect(securityEnv).not.toContain("EIDO_")
    expect(await read("security.calls")).toBe(
      [
        "find-generic-password -s com.eido.gate.keychain-unlock /Library/Keychains/System.keychain",
        "find-generic-password -s com.eido.gate.keychain-unlock -w /Library/Keychains/System.keychain",
        "",
      ].join("\n")
    )
    expect(existsSync(join(cwd, "pwned"))).toBe(false)
    expect(existsSync(join(dir, "pwned"))).toBe(false)
  })

  it("starts the gate with empty stdin and a message on stderr when the item is missing", async () => {
    await rm(join(dir, "item"), { force: true })
    const { pid, code, stderr, read } = await run()
    expect(code).toBe(0)
    expect(stderr).toBe(
      "eido gate launcher: the System keychain item com.eido.gate.keychain-unlock is missing or unreadable; starting the gate with no passphrase, so it stays locked\n"
    )
    expect(await read("gate.stdin")).toBe("")
    expect(await read("gate.tty")).toBe("notty\n")
    expect(await read("gate.pid")).toBe(`${String(pid)}\n`)
    expect(await read("security.calls")).toBe(
      "find-generic-password -s com.eido.gate.keychain-unlock /Library/Keychains/System.keychain\n"
    )
    expect(await read("gate.env")).toContain(
      "EIDO_GATE_KEYCHAIN_UNLOCK=stdin\n"
    )
  })
})
