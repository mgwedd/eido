// The parser broker's part of the plane split (#818, decided in #778): a third hidden user,
// `_eidoparse`, that runs the broker (`packages/core/src/parsers/broker-main.ts`, #817) under
// `parser.sb` with its own pf rules. The user is not in `_eidoipc`, so the modes on the gate's
// run dir and the data plane's data dir close the gate socket and `eido-data.db` to it. Its socket
// directory is owned by `_eidoparse` with the group `_eidodata`: a socket created there takes
// the directory's group, the broker sets it to 0660, and the data plane's user is the only
// member of that group, so only core can connect. Pure functions; `plane.ts` wires them in.
import { PLANE_LOGS, sbplString, type DaemonSpec } from "./plane-base.ts"

export const PARSER_NAME = "_eidoparse"
export const PARSER_LABEL = "com.eido.plane.parser"

export type ParserPaths = {
  /** The service user's home: `HOME` for the broker and its parse children. */
  home: string
  /** The broker's private scratch root (documents in flight, child work dirs). */
  scratchDir: string
  /** Owned by `_eidoparse`, group `_eidodata`, 0750: the only way in to the socket. */
  runDir: string
  socket: string
  logs: string
}

export function parserPaths(root: string, homeRoot: string): ParserPaths {
  const runDir = `${root}/parser-run`
  return {
    home: `${homeRoot}/parser`,
    scratchDir: `${root}/parser`,
    runDir,
    socket: `${runDir}/parser.sock`,
    logs: `${PLANE_LOGS}/parser`,
  }
}

export type OwnedDir = {
  path: string
  owner: string
  group: string
  mode: number
}

/** The parser's directories, in creation order. `dataGroup` is the data plane's own group. */
export function parserDirs(paths: ParserPaths, dataGroup: string): OwnedDir[] {
  return [
    { path: paths.home, owner: PARSER_NAME, group: PARSER_NAME, mode: 0o700 },
    {
      path: paths.scratchDir,
      owner: PARSER_NAME,
      group: PARSER_NAME,
      mode: 0o700,
    },
    { path: paths.runDir, owner: PARSER_NAME, group: dataGroup, mode: 0o750 },
    { path: paths.logs, owner: PARSER_NAME, group: "admin", mode: 0o750 },
  ]
}

/**
 * The parser's sandbox: the broker and every parse child it starts. No network, DNS included
 * (mDNSResponder is reached over a Unix socket), except binding and accepting on the broker's
 * own socket, which the broker needs to serve core at all.
 */
export function parserProfile(paths: ParserPaths): string {
  return [
    "(version 1)",
    "; Eido document parsers (#43, #70, #818): generated by `host plane`; no network but the broker's own socket.",
    "(allow default)",
    "(deny network*)",
    `(allow network-bind network-inbound (local unix-socket (path-literal ${sbplString(paths.socket)})))`,
    "",
  ].join("\n")
}

/**
 * pf rules for the parser user: every TCP and UDP packet it sends or receives is blocked, so a
 * parse child that inherits `parser.sb` has no loopback reach to the egress proxy or the llama
 * port either. They match the numeric uid, so they parse before the user exists.
 */
export function parserPfRules(uid: number): string[] {
  const id = String(uid)
  return [
    `# uid ${id} is ${PARSER_NAME}: no network at all.`,
    `block return quick proto { tcp, udp } from any to any user ${id}`,
  ]
}

export type ParserServiceInput = {
  paths: ParserPaths
  profile: string
  /** The plane's app copy: the broker runs from `packages/core` there. */
  app: string
  node: string
  path: string
}

/**
 * The broker's LaunchDaemon. The broker does not load the no-network preload itself (#817), so
 * the daemon loads it with `--import` before the entry, as `broker-main.test.ts` does.
 */
export function parserService(input: ParserServiceInput): DaemonSpec {
  const { paths } = input
  return {
    label: PARSER_LABEL,
    user: PARSER_NAME,
    group: PARSER_NAME,
    args: [
      "/usr/bin/sandbox-exec",
      "-f",
      input.profile,
      input.node,
      "--disable-warning=ExperimentalWarning",
      "--import",
      "./src/ts-hooks.ts",
      "--import",
      "./src/parsers/no-network.ts",
      "./src/parsers/broker-main.ts",
    ],
    cwd: `${input.app}/packages/core`,
    env: {
      EIDO_PARSER_SOCKET: paths.socket,
      EIDO_PARSER_SCRATCH_DIR: paths.scratchDir,
      HOME: paths.home,
      PATH: input.path,
    },
    outLog: `${paths.logs}/parser.out.log`,
    errLog: `${paths.logs}/parser.err.log`,
    keepAlive: true,
  }
}

/** Everything apply creates for the parser that `rm -rf` takes back, so no `_eidoparse` file stays. */
export function parserRemovePaths(paths: ParserPaths): string[] {
  return [paths.runDir, paths.scratchDir, paths.home, paths.logs]
}
