// The gate's root launch step (#823, decided in #780): launchd starts a fixed, generated zsh script
// as root. It reads the gate keychain passphrase from a root-only item in the System keychain and
// pipes it straight into the gate's stdin, then drops to the gate user and execs the gate, which
// unlocks its own keychain from stdin (#821). The passphrase is never in a shell variable, an
// argument, the environment, a file or a log: `security` writes it into the pipe and the gate
// reads it from the other end. Pure functions; `plane.ts` wires them in.
import type { DaemonSpec, Step } from "./plane-base.ts"

/** The System keychain item's service name; the passphrase runbook (#824) creates the item. */
export const KEYCHAIN_UNLOCK_SERVICE = "com.eido.gate.keychain-unlock"
export const SYSTEM_KEYCHAIN = "/Library/Keychains/System.keychain"

/** The launcher's file name in the root-owned app dir. */
export const LAUNCHER_FILE = "gate-launcher.zsh"
/** Read and execute for everyone, write for nobody but root. */
export const LAUNCHER_MODE = 0o555

/**
 * zsh, not /bin/sh: zsh runs the last command of a pipeline in the shell itself, so `... | exec`
 * replaces the launcher with the gate. launchd then signals the gate directly, and no root shell
 * stays behind. `-f` reads no startup files but the root-owned /etc/zshenv.
 */
const ZSH = "/bin/zsh"

/** The programs the launcher runs; tests swap them for fakes, the plane uses the defaults. */
export type LauncherTools = {
  security: string
  chroot: string
  env: string
}

export const LAUNCHER_TOOLS: LauncherTools = {
  security: "/usr/bin/security",
  // With -u, -g and -G and the root `/`, chroot(8) sets the groups, the gid and the uid, then execs
  // in the same process. Without -G it would keep root's supplementary groups.
  chroot: "/usr/sbin/chroot",
  // `env -C` changes to the gate's working directory after the drop: chroot leaves it at `/`.
  env: "/usr/bin/env",
}

export type GateLauncherInput = {
  /** The user the gate runs as. */
  user: string
  /** Its primary group, then its other groups: the gate's only groups after the drop. */
  groups: readonly [string, ...string[]]
  /** The gate's working directory. */
  cwd: string
  /** The gate's program, an absolute path, then its arguments. */
  argv: readonly [string, ...string[]]
  tools?: LauncherTools
}

/** Always single-quoted, so no zsh expansion (globs, `~`, `=cmd`, `$`) applies to a value. */
function quote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`
}

/** The launcher script: what launchd runs as root for the gate daemon. */
export function gateLauncher(input: GateLauncherInput): string {
  const tools = input.tools ?? LAUNCHER_TOOLS
  const [program] = input.argv
  // `env` reads a leading NAME=value operand as an assignment, so a program path with `=` would
  // run its next argument instead.
  if (!program.startsWith("/") || program.includes("="))
    throw new Error(
      `the gate's program ${JSON.stringify(program)} must be an absolute path without "="`
    )
  const [primary] = input.groups
  const read = (extra: string[]) =>
    [
      tools.env,
      "-i",
      "HOME=/var/root",
      tools.security,
      "find-generic-password",
      "-s",
      KEYCHAIN_UNLOCK_SERVICE,
      ...extra,
      SYSTEM_KEYCHAIN,
    ]
      .map(quote)
      .join(" ")
  const gate = [
    tools.chroot,
    "-u",
    input.user,
    "-g",
    primary,
    "-G",
    input.groups.join(","),
    "/",
    tools.env,
    "-C",
    input.cwd,
    ...input.argv,
  ]
    .map(quote)
    .join(" ")
  return [
    "#!/bin/zsh -f",
    "# Eido gate launcher (#823): generated by `host plane`; edit the generator, not this file.",
    `# launchd runs it as root. It pipes the passphrase of the System keychain item ${KEYCHAIN_UNLOCK_SERVICE}`,
    `# into the gate's stdin, drops to ${input.user} and execs the gate, which unlocks its keychain (#821).`,
    "set -u",
    // No core file of the launcher or the gate can hold the passphrase.
    "ulimit -c 0",
    "export EIDO_GATE_KEYCHAIN_UNLOCK=stdin",
    // The probe prints the item's attributes, never its data; both go nowhere.
    `if ! ${read([])} >/dev/null 2>&1; then`,
    `  print -u2 -r -- ${quote(`eido gate launcher: the System keychain item ${KEYCHAIN_UNLOCK_SERVICE} is missing or unreadable; starting the gate with no passphrase, so it stays locked`)}`,
    `  exec ${gate} </dev/null`,
    "fi",
    `${read(["-w"])} | exec ${gate}`,
    "",
  ].join("\n")
}

/** The gate daemon, started as root through the launcher instead of directly as the gate user. */
export function launchedGate(gate: DaemonSpec, launcher: string): DaemonSpec {
  return {
    ...gate,
    user: "root",
    group: "wheel",
    args: [ZSH, "-f", launcher],
  }
}

/** Writes the launcher root-owned and read-only after the app copy is in place. */
export function launcherSteps(path: string, script: string): Step[] {
  return [
    { argv: ["/usr/bin/tee", path], stdin: script },
    { argv: ["/usr/sbin/chown", "root:wheel", path] },
    { argv: ["/bin/chmod", LAUNCHER_MODE.toString(8).padStart(4, "0"), path] },
  ]
}
