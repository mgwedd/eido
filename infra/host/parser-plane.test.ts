import { describe, expect, it } from "vitest"

import { egressRules } from "./egress.ts"
import { parserPaths, parserProfile } from "./parser-plane.ts"
import {
  applySteps,
  daemonPlist,
  pfAnchor,
  planeLayout,
  planeServices,
  removeSteps,
  type PlaneInput,
  type Step,
} from "./plane.ts"

const layout = planeLayout({
  owner: "owner",
  ownerHome: "/Users/owner",
  firstId: 451,
  env: {},
})

const input: PlaneInput = {
  layout,
  checkout: "/Users/owner/dev/eido",
  node: "/opt/homebrew/bin/node",
  tailnetHost: "mac.example.ts.net",
  settings: {},
  egressPort: 8790,
  allowlist: {
    hosts: ["api.example.com"],
    local: [{ host: "127.0.0.1", port: 1143 }],
  },
}

const ROOT = "/Library/Application Support/Eido"
const SOCKET = `${ROOT}/parser-run/parser.sock`
const line = (step: Step) => step.argv.join(" ")

describe("parser layout", () => {
  it("keeps the broker's scratch, socket and home inside the plane and its logs with the others", () => {
    expect(layout.parser).toEqual({
      home: `${ROOT}/home/parser`,
      scratchDir: `${ROOT}/parser`,
      runDir: `${ROOT}/parser-run`,
      socket: SOCKET,
      logs: "/Library/Logs/Eido/parser",
    })
    expect(layout.plists.parser).toBe(
      "/Library/LaunchDaemons/com.eido.plane.parser.plist"
    )
  })

  it("refuses a socket path that cannot be quoted in SBPL", () => {
    const odd = parserPaths('/tmp/a"b', "/tmp/home")
    expect(() => parserProfile(odd)).toThrow("cannot go in a sandbox profile")
  })
})

describe("parser LaunchDaemon", () => {
  const { parser } = planeServices(input)
  const plist = daemonPlist(parser)

  it("runs as _eidoparse under parser.sb, with the no-network preload loaded before the broker", () => {
    expect(plist).toContain(
      "  <key>UserName</key>\n  <string>_eidoparse</string>\n  <key>GroupName</key>\n  <string>_eidoparse</string>\n"
    )
    expect(plist).toContain(
      [
        "  <key>ProgramArguments</key>",
        "  <array>",
        "    <string>/usr/bin/sandbox-exec</string>",
        "    <string>-f</string>",
        `    <string>${ROOT}/policy/parser.sb</string>`,
        "    <string>/opt/homebrew/bin/node</string>",
        "    <string>--disable-warning=ExperimentalWarning</string>",
        "    <string>--import</string>",
        "    <string>./src/ts-hooks.ts</string>",
        "    <string>--import</string>",
        "    <string>./src/parsers/no-network.ts</string>",
        "    <string>./src/parsers/broker-main.ts</string>",
        "  </array>",
        "  <key>WorkingDirectory</key>",
        `  <string>${ROOT}/app/packages/core</string>`,
      ].join("\n")
    )
    expect(plist).toContain("  <key>KeepAlive</key>\n  <true/>\n")
  })

  it("gives the broker its socket, its private scratch dir and its own home, and nothing of the stack's settings", () => {
    expect(parser.env).toEqual({
      EIDO_PARSER_SOCKET: SOCKET,
      EIDO_PARSER_SCRATCH_DIR: `${ROOT}/parser`,
      HOME: `${ROOT}/home/parser`,
      PATH: "/usr/bin:/bin:/usr/sbin:/sbin",
    })
    expect(parser.errLog).toBe("/Library/Logs/Eido/parser/parser.err.log")
  })

  it("points core at the same socket", () => {
    expect(planeServices(input).core.env["EIDO_PARSER_SOCKET"]).toBe(SOCKET)
  })
})

describe("parser pf rules", () => {
  it("blocks every TCP and UDP packet of the _eidoparse uid after the data user's rules, which stay as they were", () => {
    const rules = pfAnchor(layout, { core: 8789, egress: 8790, llama: 8080 })
    expect(rules.split("\n")).toEqual([
      "# Eido plane split (#70), anchor com.apple/eido.plane: generated by `host plane`.",
      "# uid 452 is _eidodata.",
      "pass out quick on lo0 inet proto tcp from any to 127.0.0.1 port { 8790, 8080 } user 452 flags S/SA keep state",
      "block return out quick proto tcp from any to any user 452 flags S/SA",
      "block return out quick proto udp from any to any user 452",
      "# uid 454 is _eidoparse: no network at all.",
      "block return quick proto { tcp, udp } from any to any user 454",
      "",
    ])
  })

  it("leaves the gate's egress anchor without the parser uid", () => {
    const tee = applySteps(input).find(
      (step) => line(step) === `/usr/bin/tee ${layout.egressRules}`
    )
    expect(tee?.stdin).toBe(
      egressRules({ uid: 451, local: input.allowlist.local })
    )
    expect(tee?.stdin).not.toContain("454")
  })
})

describe("parser socket access", () => {
  const steps = applySteps(input)
  const all = steps.map(line)

  it("makes _eidoparse own the socket dir with _eidodata as its only group, closed to everyone else", () => {
    expect(all).toContain(
      `/usr/sbin/chown _eidoparse:_eidodata ${ROOT}/parser-run`
    )
    expect(all).toContain(`/bin/chmod 0750 ${ROOT}/parser-run`)
  })

  it("grants the socket to no one else: no ACL entry, and only the gate and data users in the gate's socket group", () => {
    expect(
      all.filter((text) => text.includes("+a") && text.includes("parser"))
    ).toEqual([])
    expect(
      all.filter((text) => /\+a\s_eidoparse|\+a.*_eidodata/.test(text))
    ).toEqual([])
    expect(all).toContain(
      "/usr/bin/dscl . -create /Groups/_eidoipc GroupMembership _eidogate _eidodata"
    )
    expect(
      all.filter(
        (text) =>
          text.includes("GroupMembership") && text.includes("_eidoparse")
      )
    ).toEqual([])
  })

  it("lets core connect to the broker's socket and the parser sandbox bind it", () => {
    const written = (path: string) =>
      steps.find((step) => line(step) === `/usr/bin/tee ${path}`)?.stdin
    expect(written(layout.coreProfile)).toContain(
      `(allow network-outbound (remote unix-socket (path-literal "${SOCKET}")))\n`
    )
    expect(written(layout.parserProfile)).toContain(
      `(allow network-bind network-inbound (local unix-socket (path-literal "${SOCKET}")))\n`
    )
    expect(written(layout.parserProfile)).not.toContain("network-outbound")
  })
})

describe("parser apply and remove", () => {
  const steps = applySteps(input)
  const all = steps.map(line)
  const at = (text: string) => {
    const index = all.indexOf(text)
    expect(index, text).toBeGreaterThanOrEqual(0)
    return index
  }

  it("creates the group and a hidden, locked user with no shell before anything is chowned to it", () => {
    const group = at(
      "/usr/bin/dscl . -create /Groups/_eidoparse PrimaryGroupID 454"
    )
    const uid = at("/usr/bin/dscl . -create /Users/_eidoparse UniqueID 454")
    expect(all).toContain(
      "/usr/bin/dscl . -create /Users/_eidoparse PrimaryGroupID 454"
    )
    expect(all).toContain(
      "/usr/bin/dscl . -create /Users/_eidoparse Password *"
    )
    expect(all).toContain(
      "/usr/bin/dscl . -create /Users/_eidoparse UserShell /usr/bin/false"
    )
    expect(all).toContain(
      "/usr/bin/dscl . -create /Users/_eidoparse IsHidden 1"
    )
    expect(all).toContain(
      `/usr/bin/dscl . -create /Users/_eidoparse NFSHomeDirectory ${ROOT}/home/parser`
    )
    const firstChown = all.findIndex((text) =>
      text.startsWith("/usr/sbin/chown _eidoparse")
    )
    expect(group).toBeLessThan(uid)
    expect(uid).toBeLessThan(firstChown)
  })

  it("gives the broker private home and scratch dirs and its own logs dir", () => {
    for (const path of [`${ROOT}/home/parser`, `${ROOT}/parser`]) {
      expect(all).toContain(`/usr/sbin/chown _eidoparse:_eidoparse ${path}`)
      expect(all).toContain(`/bin/chmod 0700 ${path}`)
    }
    expect(all).toContain(
      "/usr/sbin/chown _eidoparse:admin /Library/Logs/Eido/parser"
    )
    // The plane's root and home root are created first, so `mkdir -p` makes no root-owned parent.
    expect(at(`/bin/mkdir -p ${ROOT}/home`)).toBeLessThan(
      at(`/bin/mkdir -p ${ROOT}/home/parser`)
    )
  })

  it("checks parser.sb and the anchor, then starts the broker after the gate and before core", () => {
    const checked = at(
      `/usr/bin/sandbox-exec -f ${ROOT}/policy/parser.sb /usr/bin/true`
    )
    const lint = at(
      "/usr/bin/plutil -lint /Library/LaunchDaemons/com.eido.plane.parser.plist"
    )
    const parser = at(
      "/bin/launchctl bootstrap system /Library/LaunchDaemons/com.eido.plane.parser.plist"
    )
    expect(checked).toBeLessThan(parser)
    expect(lint).toBeLessThan(parser)
    expect(
      at(
        "/bin/launchctl bootstrap system /Library/LaunchDaemons/com.eido.plane.gate.plist"
      )
    ).toBeLessThan(parser)
    expect(parser).toBeLessThan(
      at(
        "/bin/launchctl bootstrap system /Library/LaunchDaemons/com.eido.plane.core.plist"
      )
    )
  })

  it("stops core before the broker, then deletes the user, its group and every parser path, leaving no _eidoparse residue", () => {
    const applied = {
      users: new Map([
        ["_eidogate", 451],
        ["_eidodata", 452],
        ["_eidoparse", 454],
      ]),
      groups: new Map([
        ["_eidogate", 451],
        ["_eidodata", 452],
        ["_eidoipc", 453],
        ["_eidoparse", 454],
      ]),
    }
    const removal = removeSteps(layout, applied)
    const removed = removal.map(line)
    const stop = (label: string) =>
      removed.indexOf(`/bin/launchctl bootout system/${label}`)
    expect(stop("com.eido.plane.core")).toBeLessThan(
      stop("com.eido.plane.parser")
    )
    expect(stop("com.eido.plane.parser")).toBeLessThan(
      stop("com.eido.plane.gate")
    )
    expect(removed).toContain(
      "/bin/rm -f /Library/LaunchDaemons/com.eido.plane.parser.plist"
    )
    expect(removed).toContain("/sbin/pfctl -a com.apple/eido.plane -F all")
    const userGone = removed.indexOf(
      "/usr/bin/dscl . -delete /Users/_eidoparse"
    )
    const groupGone = removed.indexOf(
      "/usr/bin/dscl . -delete /Groups/_eidoparse"
    )
    expect(stop("com.eido.plane.parser")).toBeLessThan(userGone)
    expect(userGone).toBeLessThan(groupGone)
    expect(removed).toContain(
      `/bin/rm -rf ${ROOT}/parser-run ${ROOT}/parser ${ROOT}/home/parser /Library/Logs/Eido/parser`
    )
    // Every path apply chowns to the parser user goes.
    const owned = steps
      .filter((step) => step.argv[0] === "/usr/sbin/chown")
      .filter((step) => (step.argv[1] ?? "").startsWith("_eidoparse:"))
      .map((step) => step.argv[2])
    const deleted = removal
      .filter((step) => step.argv[0] === "/bin/rm" && step.argv[1] === "-rf")
      .flatMap((step) => step.argv.slice(2))
    expect(owned.filter((path) => !deleted.includes(path ?? ""))).toEqual([])
  })

  it("deletes no parser account that does not exist", () => {
    const removed = removeSteps(layout, {
      users: new Map(),
      groups: new Map(),
    }).map(line)
    expect(removed.filter((text) => text.includes("_eidoparse"))).toEqual([])
  })
})
