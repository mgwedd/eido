import { execFileSync, spawnSync } from "node:child_process"
import { chmodSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

import { REVIEWED_MANIFESTS } from "@eido/schemas"
import { describe, expect, it } from "vitest"

import {
  egressHostList,
  egressJob,
  egressRules,
  egressTargets,
  isHostName,
} from "./egress.ts"

/** A committed manifest with no remote hosts, its local endpoints replaced: valid in every other field. */
function withLocal(name: string, local: unknown): unknown {
  const manifest = structuredClone(REVIEWED_MANIFESTS[name])
  if (typeof manifest !== "object" || manifest === null)
    throw new Error(`no ${name} manifest`)
  return { ...manifest, egress: { hosts: [], local } }
}

describe("isHostName", () => {
  it("takes plain DNS names and refuses wildcards, IP literals, ports and single labels", () => {
    expect(isHostName("gmail.googleapis.com")).toBe(true)
    expect(isHostName("a-b.example.com")).toBe(true)
    expect(isHostName("*.googleapis.com")).toBe(false)
    expect(isHostName("203.0.113.7")).toBe(false)
    expect(isHostName("api.example.com:443")).toBe(false)
    expect(isHostName("localhost")).toBe(false)
    expect(isHostName("-bad.example.com")).toBe(false)
    expect(isHostName("Upper.example.com")).toBe(false)
    expect(isHostName(`${"a".repeat(64)}.example.com`)).toBe(false)
  })
})

describe("egressTargets", () => {
  it("lists the committed manifests' hosts with the gate's own, and the Bridge ports on loopback", () => {
    expect(egressTargets(REVIEWED_MANIFESTS)).toEqual({
      hosts: [
        "bridge.simplefin.org",
        "gmail.googleapis.com",
        "oauth2.googleapis.com",
        "web.push.apple.com",
        "www.googleapis.com",
      ],
      local: [
        { host: "127.0.0.1", port: 1025 },
        { host: "127.0.0.1", port: 1143 },
      ],
    })
  })

  it("lowercases names, drops a trailing dot and lists each host and endpoint once", () => {
    const manifests = {
      gmail: REVIEWED_MANIFESTS["gmail"],
      "gmail-again": REVIEWED_MANIFESTS["gmail"],
      "proton-mail": REVIEWED_MANIFESTS["proton-mail"],
      "proton-again": REVIEWED_MANIFESTS["proton-mail"],
    }
    expect(
      egressTargets(manifests, [
        { host: "API.Example.com." },
        { host: "gmail.googleapis.com" },
      ])
    ).toEqual({
      hosts: [
        "api.example.com",
        "gmail.googleapis.com",
        "oauth2.googleapis.com",
      ],
      local: [
        { host: "127.0.0.1", port: 1025 },
        { host: "127.0.0.1", port: 1143 },
      ],
    })
  })

  it("stops on every name pf cannot take and every manifest that does not validate, naming each", () => {
    const manifests = {
      "proton-mail": withLocal("proton-mail", [
        { protocol: "imap", host: "localhost", port: 1143 },
      ]),
      broken: { name: "broken" },
    }
    expect(() =>
      egressTargets(manifests, [{ host: "bad host" }, { host: "203.0.113.7" }])
    ).toThrow(
      'the base list: "bad host" is not a host name; ' +
        'the base list: "203.0.113.7" is not a host name; ' +
        "the broken manifest is not a valid connector manifest; " +
        "proton-mail: local endpoint localhost:1143 is not 127.0.0.1 or ::1"
    )
  })
})

describe("egressRules", () => {
  it("passes the gate user to the table on 443 and to the loopback ports, then blocks the rest", () => {
    expect(
      egressRules({
        uid: 451,
        local: [
          { host: "127.0.0.1", port: 1025 },
          { host: "127.0.0.1", port: 1143 },
          { host: "::1", port: 1143 },
        ],
      })
    ).toBe(
      [
        "# Eido gate egress allowlist (#471), anchor com.apple/eido.egress: generated by `host plane`.",
        "# uid 451 is the gate user. The egress job fills <eido_egress> from the host list.",
        "table <eido_egress> persist",
        "pass out quick proto tcp from any to <eido_egress> port 443 user 451 flags S/SA keep state",
        "pass out quick on lo0 proto tcp from any to 127.0.0.1 port { 1025, 1143 } user 451 flags S/SA keep state",
        "pass out quick on lo0 proto tcp from any to ::1 port { 1143 } user 451 flags S/SA keep state",
        "block return out quick proto tcp from any to any user 451 flags S/SA",
        "block return out quick proto udp from any to any user 451",
        "",
      ].join("\n")
    )
  })

  it("has no loopback pass when no manifest has a local endpoint", () => {
    expect(egressRules({ uid: 461, local: [] })).not.toContain("lo0")
  })
})

describe("egressHostList", () => {
  it("writes one host per line", () => {
    expect(egressHostList(["a.example.com", "b.example.com"])).toBe(
      "a.example.com\nb.example.com\n"
    )
  })
})

// The job is /bin/sh; run it against a fake pfctl that logs its arguments.
describe.skipIf(process.platform === "win32")("egressJob", () => {
  function machine(options: { loaded: boolean; loadFails?: boolean }) {
    const dir = mkdtempSync(join(tmpdir(), "eido-egress-"))
    const log = join(dir, "log")
    const pfctl = join(dir, "pfctl")
    writeFileSync(log, "")
    writeFileSync(
      pfctl,
      [
        "#!/bin/sh",
        `echo "$*" >> '${log}'`,
        'case "$*" in',
        `  *" -sr") ${options.loaded ? 'echo "pass out quick"' : "true"} ;;`,
        `  *" -f "*) exit ${options.loadFails === true ? "1" : "0"} ;;`,
        '  *"-T add bad.example.com") echo "no IP address found" >&2; exit 1 ;;',
        "esac",
        "",
      ].join("\n")
    )
    chmodSync(pfctl, 0o755)
    const hosts = join(dir, "eido egress.hosts")
    writeFileSync(
      hosts,
      egressHostList(["a.example.com", "bad.example.com", "c.example.com"])
    )
    const script = egressJob({
      rules: join(dir, "eido egress.pf"),
      hosts,
      pfctl,
    })
    const result = spawnSync("/bin/sh", ["-c", script], { encoding: "utf8" })
    const calls = readFileSync(log, "utf8")
      .trimEnd()
      .split("\n")
      .map((call) => call.replace(dir, "<dir>"))
    return { result, calls }
  }

  it("loads an empty anchor, then adds every host and reports the one that does not resolve", () => {
    const { result, calls } = machine({ loaded: false })
    expect(calls).toEqual([
      "-q -a com.apple/eido.egress -sr",
      "-q -a com.apple/eido.egress -f <dir>/eido egress.pf",
      "-q -a com.apple/eido.egress -t eido_egress -T add a.example.com",
      "-q -a com.apple/eido.egress -t eido_egress -T add bad.example.com",
      "-q -a com.apple/eido.egress -t eido_egress -T add c.example.com",
    ])
    expect(result.stderr).toContain("egress: bad.example.com was not added")
    expect(result.status).toBe(0)
  })

  it("leaves loaded rules alone and only adds hosts", () => {
    const { calls } = machine({ loaded: true })
    expect(calls.some((call) => call.includes(" -f "))).toBe(false)
    expect(calls).toHaveLength(4)
  })

  it("fails without adding hosts when the rules do not load", () => {
    const { result, calls } = machine({ loaded: false, loadFails: true })
    expect(result.status).toBe(1)
    expect(calls.some((call) => call.includes("-T add"))).toBe(false)
  })
})

// The plan's anchor must parse with the real pfctl; `-n` parses without root on macOS.
describe.skipIf(process.platform !== "darwin")(
  "egressRules on this Mac",
  () => {
    it("parses with pfctl -n", () => {
      const dir = mkdtempSync(join(tmpdir(), "eido-egress-pf-"))
      const file = join(dir, "eido-egress.pf")
      writeFileSync(
        file,
        egressRules({
          uid: 451,
          local: egressTargets(REVIEWED_MANIFESTS).local,
        })
      )
      const out = execFileSync(
        "/sbin/pfctl",
        ["-n", "-a", "com.apple/eido.egress", "-f", file, "-v"],
        { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }
      )
      expect(out).toContain("block return out quick proto udp all user = 451")
    })
  }
)
