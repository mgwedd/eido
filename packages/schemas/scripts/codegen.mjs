// Generates src/generated/types.ts from schemas/*.schema.json.
// Dependency-free on purpose: this runs in CI and near the gate's type surface.
// Run: node packages/schemas/scripts/codegen.mjs

import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = join(here, "..")
const schemaDir = join(pkgRoot, "schemas")
const outFile = join(pkgRoot, "src", "generated", "types.ts")

function pascalCase(name) {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")
}

function propertyKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
}

function typeOf(schema, depth = 0) {
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ")
  }

  switch (schema.type) {
    case "string":
      return "string"
    case "number":
    case "integer":
      return "number"
    case "boolean":
      return "boolean"
    case "null":
      return "null"
    case "array":
      return `Array<${schema.items ? typeOf(schema.items, depth) : "unknown"}>`
    case "object":
      return objectType(schema, depth)
    default:
      return "unknown"
  }
}

// Renders an object schema as an inline TypeScript object type.
function objectType(schema, depth) {
  const properties = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  const keys = Object.keys(properties)

  if (keys.length === 0) {
    return "Record<string, unknown>"
  }

  const indent = "  ".repeat(depth + 1)
  const lines = keys.map((key) => {
    const optional = required.has(key) ? "" : "?"
    return `${indent}${propertyKey(key)}${optional}: ${typeOf(properties[key], depth + 1)}`
  })

  return `{\n${lines.join("\n")}\n${"  ".repeat(depth)}}`
}

function declare(name, schema) {
  const description = schema.description
    ? `/** ${schema.description.replace(/\*\//g, "*\\/")} */\n`
    : ""

  if (schema.type === "object" || schema.properties) {
    return `${description}export interface ${name} ${objectType(schema, 0)}\n`
  }

  return `${description}export type ${name} = ${typeOf(schema)}\n`
}

const files = readdirSync(schemaDir)
  .filter((file) => file.endsWith(".schema.json"))
  .sort()

const declarations = files.map((file) => {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"))
  const base = file.replace(/\.schema\.json$/, "")
  const name = pascalCase(schema.title ?? base)
  return declare(name, schema)
})

const output = [
  "// Generated by packages/schemas/scripts/codegen.mjs from schemas/*.schema.json.",
  "// Do not edit by hand; change the JSON Schema and re-run the codegen script.",
  "",
  ...declarations,
].join("\n")

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, output)
console.log(`codegen: wrote ${outFile} (${files.length} schema(s))`)
